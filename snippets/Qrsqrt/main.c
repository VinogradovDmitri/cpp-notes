// +-  [-127, 128]        [2^31-1, 0]          | 0.0101 = 1.01 * 2^(-3) = 0 01111000 01001010111101001111000
//  0    00000000    00000000000000000000000   | 11'000 = 1.1 * 2^4     = 0 10001100 01010111110000000000000
// sgn      E                  M               | 0 10000011 10000000000000000000000 +{ 1/2 1/4 1/8 1/16 1/32 1/64 ...
// num = (-1)^sgn * 2^E * 1.M                  |  =131-127=4                            32  16   8    4    2
// bit representation |=  2^23 * E + M         | +   2^4  *  1.5        
// num = ( 1 + M * 2^(-23) ) * 2^(E-127)
// log_2 [( 1 + M * 2^(-23) ) * 2^(E-127)] = log_2 [1 + M * 2^(-23)] + E - 127 =    \ log_2 [1+x] ~ x + u, u = +0.0430
// = M * 2^(-23) + u + E - 127 = 2^(-23) * ( 2^23 * E + M ) + u - 127 =>
// => bit repr ~ log_2 (num)

// Г = 1/sqrt(y)
// log_2 (Г) = log_2 ( 1/sqrt(y) ) = (-1/2) * log_2 (y) =>
// =>  2^(-23) * ( 2^23 * E_г + M_г ) + u - 127 = (-1/2) * [2^(-23) * ( 2^23 * E_y + M_y ) + u - 127]
// 2^23 * E_г + M_г = { 3/2 * 2^23 * (127-u) } - 1/2 * ( 2^23 * E_y + M_y )
//                                  0x5f3759df -                   (i >> 1)

//

float Qrsqrt(float n) {
    long i;
    float x2, y;
    const float threehalfs = 1.5F;

    x2 = n * 0.5F;
    y = n;
    i = *(long*)&y;                             // bit repr | i ~ log_2 (y)
    i = 0x5f3759df - (i >> 1);                  // log_2 (y) * (-1/2) = log_2 ( y^(-1/2) )
    y = *(float*)&i;                            // aprox
    y = y * (threehalfs - (x2 * y * y));        // Newtow approx | ~1% err
    // y = y * ( threehalfs - ( x2 * y * y ) );

    return y;
}
